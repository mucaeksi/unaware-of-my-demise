#!/usr/bin/env node
/* global console, process */
// Google Drive's file system cannot hold symlinks/junctions, so `npm install` cannot link the workspace packages
// (EISDIR symlink). This writes tiny re-export packages in node_modules/@uomd/* instead — for types AND runtime —
// so Vite, vitest, tsx and Wrangler always run the live packages/*/src code. (A previous workaround shipped a
// pre-bundled index.js snapshot, which silently went stale whenever packages/* changed.)
//   node tools/link_workspaces.mjs          write/refresh the links
//   node tools/link_workspaces.mjs --check  fail if any link is missing or stale
import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const check = process.argv.includes('--check');
const problems = [];

for (const dir of ['packages']) {
  for (const name of readdirSafe(join(ROOT, dir))) {
    const pkgDir = join(ROOT, dir, name);
    const pkgFile = join(pkgDir, 'package.json');
    if (!existsSync(pkgFile)) continue;
    const pkg = JSON.parse(readFileSync(pkgFile, 'utf8'));
    const entry = typeof pkg.exports === 'string' ? pkg.exports : pkg.exports?.['.'];
    if (!pkg.name?.startsWith('@uomd/') || typeof entry !== 'string') continue;
    const linkDir = join(ROOT, 'node_modules', ...pkg.name.split('/'));
    const target = relative(linkDir, join(pkgDir, entry)).replaceAll('\\', '/');
    const files = {
      'package.json': `${JSON.stringify({ name: pkg.name, version: pkg.version, type: 'module', main: './index.js', types: './index.d.ts', exports: { '.': { types: './index.d.ts', default: './index.js' } } }, null, 2)}\n`,
      'index.js': `// generated by tools/link_workspaces.mjs — live re-export of ${dir}/${name}\nexport * from '${target}';\n`,
      'index.d.ts': `export * from '${target}';\n`
    };
    for (const [file, text] of Object.entries(files)) {
      const path = join(linkDir, file);
      const current = existsSync(path) ? readFileSync(path, 'utf8') : null;
      if (current === text) continue;
      if (check) problems.push(`${pkg.name}/${file}`);
      else {
        mkdirSync(linkDir, { recursive: true });
        writeFileSync(path, text);
      }
    }
  }
}

if (check && problems.length) {
  console.error(`workspace links stale or missing: ${problems.join(', ')} — run node tools/link_workspaces.mjs`);
  process.exit(1);
}
console.log(check ? 'workspace links OK' : 'workspace links written');

function readdirSafe(dir) {
  try {
    return readdirSync(dir);
  } catch {
    return [];
  }
}
