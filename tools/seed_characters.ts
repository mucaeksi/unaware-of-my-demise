/**
 * Generates apps/api/seed/characters.sql from the preserved narrative runtime data
 * (narrative/09_VN_Scripts/Runtime_Snapshot/game/data/content/characters_part1.json).
 * D1 becomes the editable authority; the narrative files stay the provenance.
 */
import { writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { ROOT, readJson } from './lib/fsutil';

interface Char {
  character_id: string;
  name_en: string;
  age: number;
  rarity: number;
  element: string;
  combat_role: string;
  acquisition: string;
  base_stats_level_1: { hp: number; atk: number; def: number; spd: number };
}
const data = readJson<{ characters: Char[] }>('narrative/09_VN_Scripts/Runtime_Snapshot/game/data/content/characters_part1.json');
const q = (s: string): string => `'${s.replace(/'/g, "''")}'`;
const lines = [
  '-- Generated by tools/seed_characters.ts from the narrative runtime snapshot. Re-runnable (keeps edited rows).',
  ...data.characters.map(
    (c) =>
      `INSERT INTO characters (id, name_en, rarity, element, role, age, acquisition, base_hp, base_atk, base_def, base_spd) VALUES (${q(c.character_id)}, ${q(c.name_en)}, ${c.rarity}, ${q(c.element)}, ${q(c.combat_role)}, ${c.age}, ${q(c.acquisition)}, ${c.base_stats_level_1.hp}, ${c.base_stats_level_1.atk}, ${c.base_stats_level_1.def}, ${c.base_stats_level_1.spd}) ON CONFLICT (id) DO NOTHING;`
  )
];
writeFileSync(join(ROOT, 'apps/api/seed/characters.sql'), `${lines.join('\n')}\n`);
console.log(`${data.characters.length} characters -> apps/api/seed/characters.sql`);
