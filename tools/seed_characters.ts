/**
 * Generates apps/api/seed/characters.sql from the preserved narrative runtime data and the D-27 attribute balance
 * (narrative/09_VN_Scripts/Runtime_Snapshot/game/data/content/characters_part1.json).
 * D1 becomes the editable authority; the narrative files stay the provenance.
 */
import { writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { balanceAttributes } from './lib/balance';
import { ROOT, readJson } from './lib/fsutil';

interface Char {
  character_id: string;
  name_en: string;
  age: number;
  rarity: number;
  element: string;
  combat_role: string;
  acquisition: string;
}
const data = readJson<{ characters: Char[] }>('narrative/09_VN_Scripts/Runtime_Snapshot/game/data/content/characters_part1.json');
const q = (s: string): string => `'${s.replace(/'/g, "''")}'`;
/** D-27: attribute columns from content/balance/attributes.json (every playable character must be listed there) */
export function attributeColumns(id: string, rarity: number): { columns: string; values: string } {
  const a = balanceAttributes(id, rarity);
  if (!a) throw new Error(`character ${id} has no entry in content/balance/attributes.json`);
  const g = (k: 'str' | 'int' | 'vit' | 'agi'): number => a.growth?.[k] ?? 0;
  return {
    columns: 'power_stat, base_str, base_int, base_vit, base_agi, growth_str, growth_int, growth_vit, growth_agi, armor',
    values: `${q(a.power)}, ${a.base.str}, ${a.base.int}, ${a.base.vit}, ${a.base.agi}, ${g('str')}, ${g('int')}, ${g('vit')}, ${g('agi')}, ${a.armor ?? 0}`
  };
}
const lines = [
  '-- Generated by tools/seed_characters.ts from the narrative runtime snapshot + content/balance/attributes.json. Re-runnable (keeps edited rows).',
  ...data.characters.map((c) => {
    const s = attributeColumns(c.character_id, c.rarity);
    return `INSERT INTO characters (id, name_en, rarity, element, role, age, acquisition, ${s.columns}) VALUES (${q(c.character_id)}, ${q(c.name_en)}, ${c.rarity}, ${q(c.element)}, ${q(c.combat_role)}, ${c.age}, ${q(c.acquisition)}, ${s.values}) ON CONFLICT (id) DO NOTHING;`;
  })
];
if (process.argv[1]?.endsWith('seed_characters.ts')) {
  writeFileSync(join(ROOT, 'apps/api/seed/characters.sql'), `${lines.join('\n')}\n`);
  console.log(`${data.characters.length} characters -> apps/api/seed/characters.sql`);
}
