/**
 * Generates apps/api/seed/banners.sql: the canonical permanent character banner (Hall of Ancestors, active) and the five
 * limited "oath" banners (draft: an operator schedules and activates them in the Control Center).
 * Pools come from the preserved character data; rates and pity come from @uomd/economy (canon economy_part1.json).
 * Weapon banners: the permanent Hall of Armaments (selectable target among the 15 permanent signatures, active) and one limited
 * signature-weapon banner per oath (draft). Commons come from the weapon catalog (3-star / 4-star non-signature weapons).
 */
import { writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { limitedCharacterBanner, standardCharacterBanner, weaponBanner } from '@uomd/economy';
import { ROOT, readJson } from './lib/fsutil';

interface Char {
  character_id: string;
  name_en: string;
  rarity: number;
  acquisition: string;
}
const { characters } = readJson<{ characters: Char[] }>('narrative/09_VN_Scripts/Runtime_Snapshot/game/data/content/characters_part1.json');
const ids = (pred: (c: Char) => boolean): string[] => characters.filter(pred).map((c) => c.character_id);
const pools = {
  fiveStandard: ids((c) => c.acquisition === 'free_start'),
  // 4-star: gacha + the free story recruits that remain obtainable from banners; 3-star: standard banner pool + Jori (free recruit, banner copies allowed)
  four: ids((c) => c.rarity === 4),
  three: ids((c) => c.rarity === 3)
};
const oath = ids((c) => c.acquisition === 'limited_banner');
const q = (s: string): string => `'${s.replace(/'/g, "''")}'`;
const rows: string[] = [];
const hall = standardCharacterBanner('hall_of_ancestors', pools);
rows.push(`INSERT INTO banners (id, title_en, config_json, status) VALUES (${q(hall.id)}, 'Hall of Ancestors', ${q(JSON.stringify(hall))}, 'active') ON CONFLICT (id) DO NOTHING;`);
// rotation order from the canon economy file
const order = ['sister_aveline', 'sable_wren', 'nara_vell', 'mirel_quill', 'vespera_wisp'];
order.forEach((featured, i) => {
  if (!oath.includes(featured)) throw new Error(`${featured} is not a limited_banner character`);
  const name = characters.find((c) => c.character_id === featured)?.name_en ?? featured;
  const id = `oath_0${i + 1}_${featured.split('_')[0]}`;
  const b = limitedCharacterBanner(id, featured, pools);
  rows.push(`INSERT INTO banners (id, title_en, config_json, status) VALUES (${q(id)}, ${q(`Oath of ${name}`)}, ${q(JSON.stringify(b))}, 'draft') ON CONFLICT (id) DO NOTHING;`);
});
// ---- weapon banners
interface W { weapon_id: string; rarity: number; owner_character_id?: string }
const wdata = readJson<{ weapons: W[]; weapon_banners: { banner_id: string; kind: string; featured_weapon_id?: string; selected_signature_weapon_ids?: string[] }[] }>('narrative/09_VN_Scripts/Runtime_Snapshot/game/data/content/weapons_part1.json');
const commons = (r: number): string[] => wdata.weapons.filter((w) => !w.owner_character_id && w.rarity === r).map((w) => w.weapon_id);
const wpools = { four: commons(4), three: commons(3) };
const hallDef = wdata.weapon_banners.find((b) => b.banner_id === 'hall_of_armaments');
const hallSigs = hallDef?.selected_signature_weapon_ids ?? [];
if (hallSigs.length !== 15) throw new Error('Hall of Armaments must list 15 signature weapons');
const hallW = weaponBanner('hall_of_armaments_weapons', hallSigs, [], wpools, true);
rows.push(`INSERT INTO banners (id, title_en, config_json, status) VALUES (${q(hallW.id)}, 'Hall of Armaments', ${q(JSON.stringify(hallW))}, 'active') ON CONFLICT (id) DO NOTHING;`);
for (const b of wdata.weapon_banners.filter((x) => x.kind === 'limited_signature' && x.featured_weapon_id)) {
  const id = `${b.banner_id.replace(/^oath_(\d+)_.*/, 'oath_$1')}_weapon`;
  const cfg = weaponBanner(id, [b.featured_weapon_id as string], hallSigs, wpools, false);
  rows.push(`INSERT INTO banners (id, title_en, config_json, status) VALUES (${q(id)}, ${q(`Signature of ${b.banner_id.split('_').slice(2).join(' ')}`)}, ${q(JSON.stringify(cfg))}, 'draft') ON CONFLICT (id) DO NOTHING;`);
}
writeFileSync(join(ROOT, 'apps/api/seed/banners.sql'), `-- Generated by tools/seed_banners.ts. Re-runnable (never overwrites a banner an operator has edited).\n${rows.join('\n')}\n`);
console.log(`${rows.length} banners -> apps/api/seed/banners.sql`);
