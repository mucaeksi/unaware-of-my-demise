#!/usr/bin/env python3
"""Check or rewrite ``game/data/content/MANIFEST.json``: the sha256 and size of every content pack.

Adapted from LEGACY ``tools/sync_godot_content.py`` (Drive ``1gHQUZGc5ozRqu2xZXJLUBRGsSqRavkn0``, 4,268 B; MIG-0042).
LEGACY generated the packs into ``content/`` and mirrored them into the Godot project; here ``game/data/content`` is
the single authoring source (INF-021), so the tool only keeps the manifest in step with the packs. Client and server
derive the rules hash from this manifest (``server/src/release.ts`` ``rulesHash``, ``game/scripts/app/client_release.gd``),
so a pack edited without ``--write`` fails CI here and in both test suites.

    python3 tools/content_manifest.py           # --check (default): read-only; any difference = exit 1 (CI job ``content``)
    python3 tools/content_manifest.py --write   # rewrite MANIFEST.json from the packs
"""

from __future__ import annotations

import argparse
import hashlib
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CONTENT_DIR = ROOT / "game" / "data" / "content"
MANIFEST_NAME = "MANIFEST.json"


def pack_files(content_dir: Path = CONTENT_DIR) -> dict[str, bytes]:
    """{file name: bytes} of every ``*.json`` pack except the manifest (sorted)."""

    return {path.name: path.read_bytes() for path in sorted(content_dir.glob("*.json")) if path.name != MANIFEST_NAME}


def build_manifest(files: dict[str, bytes]) -> str:
    manifest = {
        "note": "Generated by tools/content_manifest.py from the packs in this folder. Do not edit by hand.",
        "source": "game/data/content",
        "files": {name: {"sha256": hashlib.sha256(data).hexdigest(), "bytes": len(data)} for name, data in files.items()},
    }
    return json.dumps(manifest, indent=2, sort_keys=True, ensure_ascii=False) + "\n"


def check(content_dir: Path = CONTENT_DIR) -> list[str]:
    """Problems between the packs and the manifest (empty = in step)."""

    path = content_dir / MANIFEST_NAME
    if not path.exists():
        return [f"{MANIFEST_NAME}: missing"]
    expected = json.loads(build_manifest(pack_files(content_dir)))["files"]
    recorded = json.loads(path.read_text(encoding="utf-8")).get("files", {})
    problems = [f"{name}: not in {MANIFEST_NAME}" for name in sorted(expected.keys() - recorded.keys())]
    problems += [f"{name}: listed in {MANIFEST_NAME} but missing" for name in sorted(recorded.keys() - expected.keys())]
    problems += [
        f"{name}: sha256/size differ from {MANIFEST_NAME}"
        for name in sorted(expected.keys() & recorded.keys())
        if expected[name] != recorded[name]
    ]
    if not problems and path.read_text(encoding="utf-8") != build_manifest(pack_files(content_dir)):
        problems.append(f"{MANIFEST_NAME}: not in the generated form (run --write)")
    return problems


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument("--check", action="store_true", help="compare only (default)")
    mode.add_argument("--write", action="store_true", help="rewrite MANIFEST.json from the packs")
    args = parser.parse_args(argv)

    files = pack_files()
    if not files:
        print(f"no content packs under {CONTENT_DIR}", file=sys.stderr)
        return 2
    if args.write:
        (CONTENT_DIR / MANIFEST_NAME).write_bytes(build_manifest(files).encode("utf-8"))
        print(f"{MANIFEST_NAME} written: {len(files)} pack(s)")
        return 0
    problems = check()
    if problems:
        print(f"{MANIFEST_NAME} is out of step with the content packs:", file=sys.stderr)
        for problem in problems:
            print(f"  - {problem}", file=sys.stderr)
        print("Run: python3 tools/content_manifest.py --write", file=sys.stderr)
        return 1
    print(f"{MANIFEST_NAME} matches the {len(files)} content pack(s).")
    return 0


if __name__ == "__main__":
    sys.exit(main())
