/**
 * Generates apps/api/seed/assets.sql from content/approved_art/entries/*.json and content/base/release.json
 * so the Control Center "Assets" page always has the latest approved art & Base AAB manifest seeded in D1.
 */
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { ROOT } from './lib/fsutil';

interface ApprovedEntry {
  asset_id: string;
  class: string;
  revision: number;
  source: { model?: string; sha256?: string };
  outputs: { path: string; sha256: string; bytes: number; width?: number; height?: number }[];
  qc?: { human?: { status?: string; by?: string; note?: string } };
  license?: { origin?: string; note?: string };
}

interface ReleaseFile {
  path: string;
  sha256: string;
  bytes: number;
  media_type: string;
  kind: string;
}

const q = (s: string): string => `'${s.replace(/'/g, "''")}'`;

const approvedByPath = new Map<string, { source: string; license: string; status: string; createdBy: string; kind: string }>();
const entriesDir = join(ROOT, 'content/approved_art/entries');
if (existsSync(entriesDir)) {
  for (const file of readdirSync(entriesDir).filter((f) => f.endsWith('.json')).sort()) {
    const entry = JSON.parse(readFileSync(join(entriesDir, file), 'utf8')) as ApprovedEntry;
    const model = entry.source.model ?? 'antigravity_generated';
    const note = entry.qc?.human?.note ? ` (${entry.qc.human.note})` : '';
    const source = `approved_art:${entry.asset_id}@r${entry.revision} [${model}]${note}`.slice(0, 300);
    const license = (entry.license?.origin ?? 'project-owned').slice(0, 100);
    const status = entry.qc?.human?.status === 'approved' ? 'approved' : 'candidate';
    const createdBy = entry.qc?.human?.by ?? 'seed';
    for (const out of entry.outputs) {
      approvedByPath.set(out.path, { source, license, status, createdBy, kind: entry.class });
    }
  }
}

const release = JSON.parse(readFileSync(join(ROOT, 'content/base/release.json'), 'utf8')) as { files: ReleaseFile[] };
const rows: string[] = [
  '-- Generated by tools/seed_assets.ts from content/base/release.json and content/approved_art/entries/*.json. Re-runnable.'
];

const seen = new Set<string>();
for (const f of release.files) {
  seen.add(f.path);
  const meta = approvedByPath.get(f.path);
  const source = meta?.source ?? (f.path.startsWith('audio/') ? 'base_audio:chirp_lyria_pack' : f.path.startsWith('art/') ? 'base_art:v0.1.2_aab' : 'base_release:rel_0001');
  const license = meta?.license ?? 'project-owned';
  const status = meta?.status ?? 'approved';
  const createdBy = meta?.createdBy ?? 'seed';
  rows.push(
    `INSERT INTO assets (path, sha256, bytes, media_type, kind, source, license, status, created_by) VALUES (${q(f.path)}, ${q(f.sha256)}, ${f.bytes}, ${q(f.media_type)}, ${q(f.kind)}, ${q(source)}, ${q(license)}, ${q(status)}, ${q(createdBy)}) ON CONFLICT (path) DO UPDATE SET sha256 = excluded.sha256, bytes = excluded.bytes, media_type = excluded.media_type, kind = excluded.kind, source = excluded.source, license = excluded.license, status = excluded.status, created_by = excluded.created_by;`
  );
}

// Include any approved_art outputs that are staged for patches (e.g., campaign archetype chibis)
if (existsSync(entriesDir)) {
  for (const file of readdirSync(entriesDir).filter((f) => f.endsWith('.json')).sort()) {
    const entry = JSON.parse(readFileSync(join(entriesDir, file), 'utf8')) as ApprovedEntry;
    for (const out of entry.outputs) {
      if (seen.has(out.path)) continue;
      seen.add(out.path);
      const meta = approvedByPath.get(out.path)!;
      const mediaType = out.path.endsWith('.webp') ? 'image/webp' : out.path.endsWith('.ogg') ? 'audio/ogg' : 'application/json';
      rows.push(
        `INSERT INTO assets (path, sha256, bytes, media_type, kind, source, license, status, created_by) VALUES (${q(out.path)}, ${q(out.sha256)}, ${out.bytes}, ${q(mediaType)}, ${q(meta.kind)}, ${q(meta.source)}, ${q(meta.license)}, ${q(meta.status)}, ${q(meta.createdBy)}) ON CONFLICT (path) DO UPDATE SET sha256 = excluded.sha256, bytes = excluded.bytes, media_type = excluded.media_type, kind = excluded.kind, source = excluded.source, license = excluded.license, status = excluded.status, created_by = excluded.created_by;`
      );
    }
  }
}

writeFileSync(join(ROOT, 'apps/api/seed/assets.sql'), `${rows.join('\n')}\n`);
console.log(`${rows.length - 1} assets -> apps/api/seed/assets.sql`);
