"""Rebuild art/MANIFEST.md from the metadata embedded in every PNG under art/.

Usage:  python3 tools/art_manifest.py
Tag a new image (writes PNG text chunks, pixels unchanged):
        python3 tools/art_manifest.py tag <file.png> id=fadyme kind=vn_bust variant=composed status=APPROVED notes="..."
"""
import sys, os
from PIL import Image, PngImagePlugin

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "art")
FIELDS = ["id", "kind", "variant", "status", "native_size", "reference", "date", "notes"]


def read_meta(path):
    im = Image.open(path)
    meta = {k[5:]: v for k, v in im.info.items() if isinstance(k, str) and k.startswith("uomd_")}
    meta.setdefault("native_size", f"{im.width}x{im.height}")
    return meta


def tag(path, pairs):
    im = Image.open(path)
    meta = {k[5:]: v for k, v in im.info.items() if isinstance(k, str) and k.startswith("uomd_")}
    for p in pairs:
        k, v = p.split("=", 1)
        meta[k] = v
    meta.setdefault("native_size", f"{im.width}x{im.height}")
    info = PngImagePlugin.PngInfo()
    for k, v in meta.items():
        info.add_text("uomd_" + k, str(v))
    im.save(path, format="PNG", pnginfo=info)


def build():
    rows = []
    for dirpath, _, files in os.walk(ROOT):
        for f in sorted(files):
            if f.lower().endswith(".png"):
                p = os.path.join(dirpath, f)
                rows.append((os.path.relpath(p, ROOT).replace(os.sep, "/"), read_meta(p)))
    rows.sort()
    out = ["# Art Manifest", "", "Generated by `tools/art_manifest.py` from the metadata embedded in each PNG (text chunks `uomd_*`). Do not edit by hand; retag the file and rebuild.", ""]
    section = None
    for rel, m in rows:
        top = rel.split("/")[0] if "/" in rel else "."
        if top != section:
            section = top
            out += ["", f"## {section}/", "", "| File | " + " | ".join(FIELDS) + " |", "|---" * (len(FIELDS) + 1) + "|"]
        out.append(f"| `{rel}` | " + " | ".join(str(m.get(k, "")).replace("|", "/") for k in FIELDS) + " |")
    open(os.path.join(ROOT, "MANIFEST.md"), "w", encoding="utf-8").write("\n".join(out) + "\n")
    print(len(rows), "images")


if __name__ == "__main__":
    if len(sys.argv) > 2 and sys.argv[1] == "tag":
        tag(sys.argv[2], sys.argv[3:])
    build()
