"""Read runtime content into the design prototype. Never writes runtime files."""
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
CONTENT = HERE.parents[2] / "game" / "data" / "content"


def read(name):
    return json.loads((CONTENT / f"{name}_part1.json").read_text())


data = {
    "characters": [
        {
            "id": c["character_id"], "name": c["name_en"], "rarity": c["rarity"],
            "element": c["element"], "role": c["combat_role"], "front": c["formation_affinity"],
            "stats": c["base_stats_level_1"],
            "skills": [{"id": s["skill_id"], "name": s["name_en"], "type": s["type"],
                        "description": s["description_en"]} for s in c["skills"]],
        } for c in read("characters")["characters"]
    ],
    "chapters": [
        {"id": c["chapter_id"], "name": c["title_en"], "nodes": [
            {"id": n["stage_id"], "title": n["title_en"], "cost": n.get("stamina_cost", 6),
             "level": n["recommended_level"]} for n in c["nodes"]]}
        for c in read("chapters")["chapters"]
    ],
    "weapons": [{"id": w["weapon_id"], "name": w["name_en"], "rarity": w["rarity"],
                 "description": w["passive_effect_en"]} for w in read("weapons")["weapons"][:5]],
    "armor": [{"id": a["armor_id"], "name": a["name_en"], "rarity": a["rarity"],
               "description": "Armor · Lv 1 · Equipment design sample"}
              for a in read("armors")["armors"][:3]],
    "codex": read("lore_text")["codex"],
    "companions": [{"id": s["character_id"], "name": s["name_en"], "parts": [
        {"id": p["story_id"], "title": p["title_en"], "unlock": p["unlock"]}
        for p in s["parts"]]} for s in read("character_stories")["stories"]],
    "events": [{"id": e["event_id"], "title": e["title_en"], "unlock": e["unlock"]}
               for e in read("events")["events"]],
    "dialogue": json.loads((CONTENT / "story_script_ch01.json").read_text())["opening_scene"]["lines"][2:6],
    "banners": {k: read("economy")["banners"][k]
                for k in ("character", "weapon", "standard_character")},
}
(HERE / "sample-data.js").write_text(
    "// Generated by sync-source-data.py; source files stay unchanged.\n"
    + "const SOURCE_DATA = " + json.dumps(data, ensure_ascii=False, indent=2) + ";\n"
)
print(f"Prototype data: {len(data['characters'])} characters, {len(data['chapters'])} chapters.")
